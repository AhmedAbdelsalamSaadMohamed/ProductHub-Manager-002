CREATE TABLE ph_sec_objects (
    object_id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    parent_object_id NUMBER(19),
    object_name      VARCHAR2(128 CHAR) NOT NULL,
    object_type_id   NUMBER(10) NOT NULL,
    object_path      VARCHAR2(300 CHAR) NOT NULL,
    display_name_en  VARCHAR2(200 CHAR) NOT NULL,
    display_name_ar  VARCHAR2(200 CHAR) NOT NULL,
    description_en   VARCHAR2(500 CHAR),
    description_ar   VARCHAR2(500 CHAR),
    is_active        NUMBER(1) DEFAULT 1 NOT NULL,
    is_deleted       NUMBER(1) DEFAULT 0 NOT NULL CHECK ( is_deleted IN (0, 1) ),
    created_by    NUMBER,
    created_at       TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by       NUMBER,
    updated_at       TIMESTAMP(3),
    deleted_by       NUMBER,
    deleted_at       TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_objects PRIMARY KEY (object_id),
    CONSTRAINT uk_ph_sec_objects_name UNIQUE (object_name),
    CONSTRAINT uk_ph_sec_objects_path UNIQUE (object_path),
    CONSTRAINT fk_ph_sec_objects_parent FOREIGN KEY (parent_object_id) REFERENCES ph_sec_objects ( object_id ),
    CONSTRAINT fk_ph_sec_objects_type FOREIGN KEY (object_type_id) REFERENCES ph_sec_object_type_lkp ( object_type_id ),
    CONSTRAINT ck_ph_sec_objects_parent CHECK ( parent_object_id IS NULL
        OR parent_object_id <> object_id )
);

