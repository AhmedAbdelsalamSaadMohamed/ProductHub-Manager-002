    description_ar  VARCHAR2(500 CHAR),
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    is_deleted      NUMBER(1) DEFAULT 0 NOT NULL CHECK ( is_deleted IN (0, 1) ),
    created_by    NUMBER,
    created_at      TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by      NUMBER,
    updated_at      TIMESTAMP(3),
    deleted_by      NUMBER,
    deleted_at      TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_actions PRIMARY KEY (action_id),
    CONSTRAINT uk_ph_sec_actions_name UNIQUE (action_name)
);

CREATE TABLE ph_sec_permissions (
    permission_id      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    object_id          NUMBER(19) NOT NULL,
    action_id          NUMBER(19) NOT NULL,
    permission_name_en VARCHAR2(200 CHAR) NOT NULL,
    permission_name_ar VARCHAR2(200 CHAR) NOT NULL,
    description_en     VARCHAR2(500 CHAR),
    description_ar     VARCHAR2(500 CHAR),
    is_active          NUMBER(1) DEFAULT 1 NOT NULL,
    is_deleted         NUMBER(1) DEFAULT 0 NOT NULL CHECK ( is_deleted IN (0, 1) ),
    created_by    NUMBER,
    created_at         TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by         NUMBER,
    updated_at         TIMESTAMP(3),
    deleted_by         NUMBER,
    deleted_at         TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_permissions PRIMARY KEY (permission_id),
    CONSTRAINT uk_ph_sec_permissions UNIQUE (object_id, action_id),
