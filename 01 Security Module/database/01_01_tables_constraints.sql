CREATE TABLE ph_sec_users (
    user_id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    customer_id          NUMBER(19),
    user_type            NUMBER(10) NOT NULL,
    email                VARCHAR2(320 CHAR) NOT NULL,
    display_name         VARCHAR2(200 CHAR) NOT NULL,
    password_hash        raw(512),
    password_salt        raw(256),
    must_change_password NUMBER(1) DEFAULT 1 NOT NULL,
    is_initial_admin     NUMBER(1) DEFAULT 0 NOT NULL,
    is_active            NUMBER(1) DEFAULT 1 NOT NULL,
    last_login_at        TIMESTAMP(3),
    is_deleted           NUMBER(1) DEFAULT 0 NOT NULL CHECK ( is_deleted IN (0, 1) ),
    created_by    NUMBER,
    created_at           TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           NUMBER,
    updated_at           TIMESTAMP(3),
    deleted_by           NUMBER,
    deleted_at           TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_users PRIMARY KEY (user_id),
    CONSTRAINT uk_ph_sec_users_email UNIQUE (email),
    CONSTRAINT fk_ph_sec_users_customer FOREIGN KEY (customer_id) REFERENCES ph_erp_customers ( customer_id ),
    CONSTRAINT fk_ph_sec_users_type FOREIGN KEY (user_type) REFERENCES ph_sec_user_type_lkp ( user_type_id ),
    CONSTRAINT ck_ph_sec_users_email_lower CHECK ( email = LOWER(email) ),
    CONSTRAINT ck_ph_sec_users_flags CHECK ( must_change_password IN (0, 1)
        AND is_initial_admin IN (0, 1) )
);

CREATE TABLE ph_sec_user_preferences (
    user_id          NUMBER(19) NOT NULL,
    preference_code  VARCHAR2(80 CHAR) NOT NULL,
    preference_value VARCHAR2(4000 CHAR),
    value_type       VARCHAR2(20 CHAR) DEFAULT 'STRING' NOT NULL,
    is_active        NUMBER(1) DEFAULT 1 NOT NULL,
    is_deleted       NUMBER(1) DEFAULT 0 NOT NULL CHECK ( is_deleted IN (0, 1) ),
    created_by    NUMBER,
    created_at       TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by       NUMBER,
    updated_at       TIMESTAMP(3),
    deleted_by       NUMBER,
    deleted_at       TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_user_preferences PRIMARY KEY (user_id, preference_code),
    CONSTRAINT fk_ph_sec_user_pref_user FOREIGN KEY (user_id) REFERENCES ph_sec_users ( user_id ),
    CONSTRAINT ck_ph_sec_user_pref_code CHECK ( preference_code = UPPER(preference_code) ),
    CONSTRAINT ck_ph_sec_user_pref_type CHECK ( value_type IN ( 'STRING',
    'NUMBER',
    'BOOLEAN',
    'JSON' ) ),
    CONSTRAINT ck_ph_sec_user_pref_active CHECK ( is_active IN (0, 1) )
);

CREATE TABLE ph_sec_refresh_tokens (
    refresh_token_id     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    user_id              NUMBER(19) NOT NULL,
    token_hash           RAW(32) NOT NULL,
    issued_at            TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at           TIMESTAMP(3) NOT NULL,
    revoked_at           TIMESTAMP(3),
    replaced_by_token_id NUMBER(19),
    created_by           NUMBER,
    created_at           TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           NUMBER,
    updated_at           TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_refresh_tokens PRIMARY KEY (refresh_token_id),
    CONSTRAINT uk_ph_sec_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_ph_sec_rt_user FOREIGN KEY (user_id) REFERENCES ph_sec_users ( user_id ),
    CONSTRAINT fk_ph_sec_rt_replaced_by FOREIGN KEY (replaced_by_token_id) REFERENCES ph_sec_refresh_tokens ( refresh_token_id ),
    CONSTRAINT ck_ph_sec_rt_dates CHECK (expires_at > issued_at)
);

CREATE TABLE ph_sec_password_reset_tokens (
    reset_token_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    user_id        NUMBER(19) NOT NULL,
    token_hash     RAW(32) NOT NULL,
    issued_at      TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at     TIMESTAMP(3) NOT NULL,
    used_at        TIMESTAMP(3),
    created_by     NUMBER,
    created_at     TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by     NUMBER,
    updated_at     TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_password_reset_tokens PRIMARY KEY (reset_token_id),
    CONSTRAINT uk_ph_sec_prt_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_ph_sec_prt_user FOREIGN KEY (user_id) REFERENCES ph_sec_users ( user_id ),
    CONSTRAINT ck_ph_sec_prt_dates CHECK (expires_at > issued_at)
);

CREATE TABLE ph_sec_apex_pages (
    apex_page_id      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    apex_app_id       NUMBER(10) NOT NULL,
    apex_page_no      NUMBER(10) NOT NULL,
    apex_page_type_id NUMBER(10) NOT NULL,
    page_alias        VARCHAR2(128 CHAR),
    page_name_en      VARCHAR2(200 CHAR) NOT NULL,
    page_name_ar      VARCHAR2(200 CHAR) NOT NULL,
    object_path       VARCHAR2(300 CHAR),
    access_mode       VARCHAR2(20 CHAR) DEFAULT 'ANY' NOT NULL,
    is_public         NUMBER(1) DEFAULT 0 NOT NULL,
    is_active         NUMBER(1) DEFAULT 1 NOT NULL,
    is_deleted        NUMBER(1) DEFAULT 0 NOT NULL CHECK ( is_deleted IN (0, 1) ),
    created_by    NUMBER,
    created_at        TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by        NUMBER,
    updated_at        TIMESTAMP(3),
    deleted_by        NUMBER,
    deleted_at        TIMESTAMP(3),
    CONSTRAINT pk_ph_sec_apex_pages PRIMARY KEY (apex_page_id),
    CONSTRAINT uk_ph_sec_apex_pages_app_page UNIQUE (apex_app_id, apex_page_no),
    CONSTRAINT uk_ph_sec_apex_pages_alias UNIQUE (apex_app_id, page_alias),
    CONSTRAINT fk_ph_sec_apex_pages_type FOREIGN KEY (apex_page_type_id) REFERENCES ph_sec_apex_page_type_lkp ( apex_page_type_id ),
    CONSTRAINT ck_ph_sec_apex_pages_ids CHECK ( apex_app_id > 0
        AND apex_page_no >= 0 ),
    CONSTRAINT ck_ph_sec_apex_pages_mode CHECK ( access_mode IN ('ANY', 'ALL') ),
    CONSTRAINT ck_ph_sec_apex_pages_flags CHECK ( is_public IN (0, 1)
        AND is_active IN (0, 1) )
);

CREATE TABLE ph_sec_apex_page_permissions (
