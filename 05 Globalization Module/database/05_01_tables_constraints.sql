CREATE TABLE ph_globalization_error_log (
    error_log_id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    error_date              TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    program_unit            VARCHAR2(128 CHAR),
    program_unit_parameters CLOB,
    error_location          VARCHAR2(4000 CHAR),
    error_code              NUMBER,
    error_message           VARCHAR2(4000 CHAR),
    error_stack             CLOB,
    error_backtrace         CLOB,
    call_stack              CLOB,
    module_name             VARCHAR2(64 CHAR) DEFAULT 'GLOBALIZATION' NOT NULL,
    action_name             VARCHAR2(64 CHAR),
    session_user            VARCHAR2(128 CHAR) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER'),
    current_schema          VARCHAR2(128 CHAR) DEFAULT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA'),
    client_identifier       VARCHAR2(256 CHAR) DEFAULT SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'),
    host_name               VARCHAR2(256 CHAR) DEFAULT SYS_CONTEXT('USERENV', 'HOST'),
    ip_address              VARCHAR2(64 CHAR) DEFAULT SYS_CONTEXT('USERENV', 'IP_ADDRESS'),
    apex_app_id             NUMBER,
    apex_page_id            NUMBER,
    created_at              TIMESTAMP(3) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ph_globalization_error_log PRIMARY KEY (error_log_id)
);

